#include "libft.h"

int	ft_atoi(const char *str)
{
	int	i;
	int	s;
	int	nb;

	s = 0;
	i = 0;
	nb = 0;
	while ((str[i] >= '\t' && str[i] <= '\r') || (str[i] == ' '))
		i++;
	if ((str[i] == '-') || (str[i] == '+'))
	{
		if (str[i] == '-')
			s++;
		i++;
	}
	while ((str[i] >= '0') && (str[i] <= '9'))
	{
		nb = str[i] - '0' + (nb * 10);
		i++;
	}
	if (!((s % 2) == 0))
		nb = (nb * (-1));
	return (nb);
}
